//! Evidence-based verification. A model summary is never a required check
//! and process success is not proof that a requested code change passed tests.

use serde::Serialize;

use crate::harness::{RunResult, RunStatus, SessionId};

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Outcome {
    Verified,
    Failed,
    Unverified,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Kind {
    StructuredSession,
    ProcessExit,
    GitStatus,
    TestProcess,
    Accessibility,
    Screen,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Authority {
    /// Structured event from an independently identified system or provider.
    Direct,
    /// Corroborating data that alone does not prove a required operation.
    Supporting,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize)]
pub struct Evidence {
    pub kind: Kind,
    pub authority: Authority,
    pub observed_at: u64,
    /// Stable identity or a bounded, opaque reference. Never raw prompts or secrets.
    pub reference: String,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Status {
    Passed,
    Failed,
    Unknown,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize)]
pub struct Check {
    pub id: String,
    pub required: bool,
    pub status: Status,
    /// Indices into the `evidence` array. A direct source is needed for
    /// required passing checks; a screenshot interpretation alone is not proof.
    pub evidence_indices: Vec<usize>,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize)]
pub struct Result {
    pub outcome: Outcome,
    pub target_id: String,
    pub operation: String,
    pub observed_at: u64,
    pub evidence: Vec<Evidence>,
    pub checks: Vec<Check>,
    /// Human-readable limitations are generated by the trusted checker, not the model.
    pub limitations: Vec<String>,
}

impl Result {
    /// Check structural evidence without allowing a caller to supply an outcome.
    pub fn evaluate(
        target_id: &str,
        operation: &str,
        observed_at: u64,
        evidence: Vec<Evidence>,
        checks: Vec<Check>,
        limitations: Vec<String>,
    ) -> std::result::Result<Self, String> {
        if target_id.trim().is_empty()
            || target_id.len() > 160
            || operation.trim().is_empty()
            || operation.len() > 80
            || evidence.len() > 64
            || checks.is_empty()
            || checks.len() > 64
            || limitations.len() > 16
            || evidence.iter().any(|item| item.reference.len() > 160)
        {
            return Err("Invalid verification size or identity".into());
        }
        let mut seen = std::collections::HashSet::new();
        for check in &checks {
            if check.id.is_empty() || check.id.len() > 80 || !seen.insert(&check.id) {
                return Err("Verification checks need unique stable IDs".into());
            }
            if check.evidence_indices.len() > 8
                || check
                    .evidence_indices
                    .iter()
                    .any(|index| *index >= evidence.len())
            {
                return Err("A verification check references nonexistent evidence".into());
            }
            if check.status == Status::Passed
                && check.required
                && !check
                    .evidence_indices
                    .iter()
                    .any(|index| evidence[*index].authority == Authority::Direct)
            {
                return Err("A required check cannot pass on inferred evidence alone".into());
            }
        }
        let required = checks
            .iter()
            .filter(|check| check.required)
            .collect::<Vec<_>>();
        let outcome = if required.iter().any(|check| check.status == Status::Failed) {
            Outcome::Failed
        } else if required.is_empty() || required.iter().any(|check| check.status != Status::Passed)
        {
            Outcome::Unverified
        } else {
            Outcome::Verified
        };
        Ok(Self {
            outcome,
            target_id: target_id.into(),
            operation: operation.into(),
            observed_at,
            evidence,
            checks,
            limitations,
        })
    }

    /// Verifies *delivery to an identified coding session*, not correctness of
    /// the agent's changes. Tests and Git diffs require separate checks.
    pub fn harness_delivery(
        result: &RunResult,
        expected: Option<&SessionId>,
        observed_at: u64,
    ) -> Self {
        let accepted = result.accepted_session.as_ref();
        let target_id = expected
            .or(accepted)
            .map_or("unresolved-session", SessionId::as_str);
        let mut evidence = Vec::new();
        let session_ack = accepted
            .filter(|session| expected.is_none_or(|wanted| wanted == *session))
            .map(|session| {
                evidence.push(Evidence {
                    kind: Kind::StructuredSession,
                    authority: Authority::Direct,
                    observed_at,
                    reference: session.as_str().to_string(),
                });
                evidence.len() - 1
            });
        if result.exit_code.is_some() {
            evidence.push(Evidence {
                kind: Kind::ProcessExit,
                authority: Authority::Direct,
                observed_at,
                reference: format!("exit:{}", result.exit_code.unwrap_or_default()),
            });
        }
        let exit_index = (!evidence.is_empty() && result.exit_code.is_some())
            .then_some(evidence.len().saturating_sub(1));
        let cancelled = result.status == RunStatus::Cancelled;
        let errored = !result.errors.is_empty() || result.status == RunStatus::Failed;
        let exit_status = if cancelled {
            Status::Unknown
        } else if errored || result.exit_code.is_some_and(|code| code != 0) {
            Status::Failed
        } else if result.exit_code == Some(0) && result.status == RunStatus::Completed {
            Status::Passed
        } else {
            Status::Unknown
        };
        let ack_status = if cancelled {
            Status::Unknown
        } else if session_ack.is_some() {
            Status::Passed
        } else {
            Status::Unknown
        };
        let checks = vec![
            Check {
                id: "structured_session_ack".into(),
                required: true,
                status: ack_status,
                evidence_indices: session_ack.into_iter().collect(),
            },
            Check {
                id: "owned_run_exit".into(),
                required: true,
                status: exit_status,
                evidence_indices: exit_index.into_iter().collect(),
            },
        ];
        let limitations = if cancelled {
            vec!["Owned run stopped; external effects may already exist".into()]
        } else if session_ack.is_none() {
            vec!["No structured acknowledgment from the requested session".into()]
        } else {
            vec!["This verifies receipt and process exit only, not code correctness".into()]
        };
        Self::evaluate(
            target_id,
            "harness_task_delivery",
            observed_at,
            evidence,
            checks,
            limitations,
        )
        .expect("Internally generated harness verification fields are valid")
    }

    /// A separate, narrow check for whether a known file change was observed in
    /// the owned Git worktree; never implies tests or code correctness.
    pub fn required_git_change(
        target_id: &str,
        changed_files: Option<&[String]>,
        expected_path: &str,
        observed_at: u64,
    ) -> std::result::Result<Self, String> {
        if expected_path.is_empty()
            || expected_path.len() > 160
            || expected_path.starts_with('/')
            || expected_path
                .split('/')
                .any(|part| part.is_empty() || part == "..")
            || expected_path.chars().any(char::is_control)
        {
            return Err("Expected a safe, project-relative path".into());
        }
        let status = match changed_files {
            None => Status::Unknown,
            Some(files) if files.iter().any(|file| file == expected_path) => Status::Passed,
            Some(_) => Status::Failed,
        };
        let evidence = changed_files.map_or_else(Vec::new, |_| {
            vec![Evidence {
                kind: Kind::GitStatus,
                authority: Authority::Direct,
                observed_at,
                reference: "git_status_snapshot".into(),
            }]
        });
        Self::evaluate(
            target_id,
            "owned_worktree_file_change",
            observed_at,
            evidence,
            vec![Check {
                id: "expected_file_changed".into(),
                required: true,
                status,
                evidence_indices: if changed_files.is_some() {
                    vec![0]
                } else {
                    vec![]
                },
            }],
            vec!["A changed file does not prove tests pass".into()],
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn run(status: RunStatus, exit: Option<i32>, accepted: bool) -> RunResult {
        RunResult {
            status,
            exit_code: exit,
            accepted_session: accepted
                .then(|| SessionId::try_from("ses_provider".to_string()).unwrap()),
            errors: vec![],
            stderr: vec![],
            changed_files: None,
        }
    }

    #[test]
    fn provider_ack_plus_successful_exit_verifies_delivery_only() {
        let result = Result::harness_delivery(&run(RunStatus::Completed, Some(0), true), None, 42);
        assert_eq!(result.outcome, Outcome::Verified);
        assert_eq!(result.operation, "harness_task_delivery");
        assert!(result.limitations[0].contains("not code correctness"));
        assert_eq!(result.evidence.len(), 2);
    }

    #[test]
    fn zero_exit_without_session_id_is_unverified() {
        let result = Result::harness_delivery(&run(RunStatus::Completed, Some(0), false), None, 5);
        assert_eq!(result.outcome, Outcome::Unverified);
    }

    #[test]
    fn wrong_target_cancel_and_nonzero_exit_never_verify() {
        let expected = SessionId::try_from("ses_expected".into()).unwrap();
        let delivered = run(RunStatus::Completed, Some(0), true);
        assert_eq!(
            Result::harness_delivery(&delivered, Some(&expected), 5).outcome,
            Outcome::Unverified
        );
        assert_eq!(
            Result::harness_delivery(&run(RunStatus::Cancelled, None, true), None, 5).outcome,
            Outcome::Unverified
        );
        assert_eq!(
            Result::harness_delivery(&run(RunStatus::Failed, Some(1), true), None, 5).outcome,
            Outcome::Failed
        );
    }

    #[test]
    fn required_checks_refuse_inferred_evidence_or_empty_requirements() {
        let empty = Result::evaluate(
            "target",
            "operation",
            0,
            vec![],
            vec![Check {
                id: "optional".into(),
                required: false,
                status: Status::Passed,
                evidence_indices: vec![],
            }],
            vec![],
        )
        .unwrap();
        assert_eq!(empty.outcome, Outcome::Unverified);
        assert!(
            Result::evaluate(
                "target",
                "operation",
                0,
                vec![Evidence {
                    kind: Kind::Screen,
                    authority: Authority::Supporting,
                    observed_at: 0,
                    reference: "screen_ref".into(),
                }],
                vec![Check {
                    id: "required".into(),
                    required: true,
                    status: Status::Passed,
                    evidence_indices: vec![0],
                }],
                vec![],
            )
            .is_err()
        );
    }

    #[test]
    fn required_git_changes_distinguish_missing_data_from_explicit_absence() {
        let files = vec!["src/lib.rs".into()];
        assert_eq!(
            Result::required_git_change("run", None, "src/lib.rs", 1)
                .unwrap()
                .outcome,
            Outcome::Unverified
        );
        assert_eq!(
            Result::required_git_change("run", Some(&files), "src/lib.rs", 1)
                .unwrap()
                .outcome,
            Outcome::Verified
        );
        assert_eq!(
            Result::required_git_change("run", Some(&files), "src/missing.rs", 1)
                .unwrap()
                .outcome,
            Outcome::Failed
        );
        assert!(Result::required_git_change("run", Some(&files), "../outside", 1).is_err());
    }
}
